"""Validated finite algorithm grammar; model text is never executed."""
from dataclasses import dataclass, asdict, fields
import json
import math
from pathlib import Path


@dataclass(frozen=True)
class Plan:
    surrogate: str = "auto"
    operator: str = "current_to_best"
    mutation: float = 0.65
    crossover: float = 0.85
    exploration: float = 0.2
    local_fraction: float = 0.3
    radius: float = 0.12
    population: int = 40
    generations: int = 6
    reason: str = "Fixed reference design."

    def __post_init__(self):
        if self.surrogate not in {"auto", "rbf", "quadratic"}:
            raise ValueError("Unknown surrogate")
        if self.operator not in {"rand1", "best1", "current_to_best"}:
            raise ValueError("Unknown evolutionary operator")
        for name, lo, hi in [("mutation", .1, 1.5), ("crossover", .05, 1.0),
                             ("exploration", 0., 2.), ("local_fraction", 0., .8),
                             ("radius", .01, .5)]:
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not lo <= value <= hi:
                raise ValueError(f"{name} must be finite and in [{lo}, {hi}]")
        for name, lo, hi in [("population", 12, 100), ("generations", 1, 20)]:
            v = getattr(self, name)
            if type(v) is not int or not lo <= v <= hi:
                raise ValueError(f"{name} must be integer in [{lo}, {hi}]")
        if not isinstance(self.reason, str) or len(self.reason) > 1000:
            raise ValueError("reason must be a short string")

    def to_dict(self):
        return asdict(self)

    @classmethod
    def from_dict(cls, data):
        if not isinstance(data, dict) or set(data) != {f.name for f in fields(cls)}:
            raise ValueError("Plan must contain exactly the supported fields")
        return cls(**data)


def plan_schema():
    properties = {
        "surrogate": {"type": "string", "enum": ["auto", "rbf", "quadratic"]},
        "operator": {"type": "string", "enum": ["rand1", "best1", "current_to_best"]},
        **{k: {"type": "number"} for k in ["mutation", "crossover", "exploration", "local_fraction", "radius"]},
        **{k: {"type": "integer"} for k in ["population", "generations"]},
        "reason": {"type": "string"},
    }
    return {"type": "object", "properties": properties,
            "required": list(properties), "additionalProperties": False}


def offline_policy(state):
    """Transparent rule-based comparator. This is NOT an LLM simulation."""
    stalled = state["stagnation"] >= 12
    progress = state["evaluations"] / state["budget"]
    return Plan(operator="rand1" if stalled else "current_to_best",
                exploration=.65 if stalled else .25*(1-progress),
                local_fraction=.15 if stalled else .5,
                radius=.25 if stalled else max(.025, .18*(1-progress)),
                reason="Offline rules: increase global exploration after 12 unimproved evaluations.")


def export_program(path, plan, provenance):
    """Generate a reviewable runnable Python algorithm from a validated plan.

    Literal serialization is the only insertion point; no model code is exec'd.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(path)
    source = ("# Generated by llm-saea. See adjacent provenance JSON.\n"
              "from llm_saea import Plan, benchmark, optimize\n\n"
              f"PLAN = Plan.from_dict({plan.to_dict()!r})\n\n"
              "def solve(problem, budget=100, seed=0):\n"
              "    return optimize(problem, budget=budget, seed=seed, method='saea', plan=PLAN)\n\n"
              "if __name__ == '__main__':\n"
              "    result = solve(benchmark('sphere', 5))\n"
              "    print({'best_y': result.best_y, 'best_x': result.best_x.tolist()})\n")
    path.write_text(source, encoding="utf-8")
    path.with_suffix(".json").write_text(json.dumps({"plan": plan.to_dict(), "provenance": provenance}, ensure_ascii=False, indent=2), encoding="utf-8")
